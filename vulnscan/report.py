    def _coverage(self, meta, coverage):
        ws = self.wb.add_worksheet("Coverage")
        cols = [("Repository", 14, "bold"), ("SVN URL", 60, None), ("Revision", 9, "center"),
                ("Last changed", 22, None), ("Files", 9, "int"), ("Size (MB)", 10, "int"),
                ("In archives", 10, "int"), ("Archives extracted", 10, "int"), ("Archives failed", 10, "int"),
                ("Binaries", 9, "int"), ("Components", 11, "int"), ("Engines", 70, None), ("Duration", 10, None),
                ("Error", 60, None)]
        rows = []
        for c in coverage:
            eng = "; ".join(f"{k}: {v.get('status')}" + (f" ({v.get('duration')})" if v.get("duration") else "")
                            + (f" - {v.get('error')}" if v.get("error") else "")
                            for k, v in c.get("engines", {}).items())
            rows.append([c["repo"], c.get("url", ""), c.get("revision", ""), c.get("last_changed", ""),
                         c.get("files", 0), int(c.get("bytes", 0) / 1048576), c.get("in_archives", 0),
                         c.get("archives_ok", 0), c.get("archives_failed", 0), c.get("binaries", 0),
                         c.get("components", 0), clean(eng), c.get("duration", ""), clean(c.get("error", ""))])
        _, last = self._table(ws, "Coverage", cols, rows, freeze_cols=1)
        r = last + 3
        sections = [
            ("Archives not (fully) extracted - contents NOT scanned",
             [(c["repo"], a, why) for c in coverage for a, why in c.get("archive_failures", [])]),
            ("Accepted coverage gaps (acknowledged in vulnscan-accepted-gaps.json)",
             [(c["repo"], a, f"{why} — accepted: {reason}") for c in coverage
              for a, why, reason in c.get("archives_acknowledged", [])]),
            ("Symbolic links in the repository (recorded, not followed)",
             [(c["repo"], link, "") for c in coverage for link in c.get("symlinks", [])]),
        ]
        for title, items in sections:
            ws.write(r, 0, title, self.f["h2"])
            r += 1
            if not items:
                ws.write(r, 0, "None", self.f["muted"])
                r += 1
            for repo, a, why in items:
                ws.write(r, 0, repo)
                ws.write(r, 1, clean(a))
                ws.write(r, 3, clean(why))
                r += 1
            r += 2
        ws.write(r, 0, "Run", self.f["h2"])
        for k, v in [("Run ID", meta["run_id"]), ("Started", meta["started"]), ("Finished", meta["finished"]),
                     ("Duration", meta["duration"]), ("Command", meta["command"]),
                     ("Raw evidence", meta["evidence_dir"])] + list(meta["tools"].items()) + list(meta["databases"].items()):
            r += 1
            ws.write(r, 0, k, self.f["bold"])
            ws.write(r, 1, clean(v))
