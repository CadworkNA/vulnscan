"""Excel report (xlsxwriter).

Sheets
  Summary          KPIs, per-repository breakdown, chart, top risks, methodology
  Findings         one row per (repository, file, vulnerability) - the full detail
  Vulnerabilities  one row per distinct vulnerability + affected component
  Components       every identified third-party component and its exposure
  End of Life      unsupported runtimes / libraries
  Binaries         every executable shipped, with vendor metadata and review flag
  Coverage         what was scanned, by which engine, and anything that failed
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict
from pathlib import Path

import xlsxwriter

SEVS = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "NEGLIGIBLE", "UNKNOWN"]
SEV_RANK = {s: i for i, s in enumerate(SEVS)}
PRIO = ["P1", "P2", "P3", "P4"]

SEV_COLORS = {"CRITICAL": ("#991B1B", "#FFFFFF"), "HIGH": ("#DC2626", "#FFFFFF"),
              "MEDIUM": ("#F59E0B", "#1F2937"), "LOW": ("#FDE68A", "#1F2937"),
              "NEGLIGIBLE": ("#E5E7EB", "#374151"), "UNKNOWN": ("#E5E7EB", "#374151")}
PRIO_COLORS = {"P1": ("#7F1D1D", "#FFFFFF"), "P2": ("#DC2626", "#FFFFFF"),
               "P3": ("#F59E0B", "#1F2937"), "P4": ("#D1D5DB", "#1F2937")}
INK, MUTED, LINE, BRAND = "#111827", "#6B7280", "#E5E7EB", "#1E3A5F"
MAX_CELL = 32000
_ILLEGAL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


_SAFE_ID = re.compile(r"^[A-Za-z0-9._:-]{1,80}$")


def vuln_url(vid: str) -> str:
    """Advisory link for a vulnerability id; empty for anything that is not a plain id
    (ids end up inside URLs and Excel formulas, so nothing else is ever linked)."""
    if not _SAFE_ID.match(vid or ""):
        return ""
    if vid.upper().startswith("CVE-"):
        return f"https://nvd.nist.gov/vuln/detail/{vid.upper()}"
    if vid.upper().startswith("GHSA-"):
        return f"https://github.com/advisories/{vid}"
    if re.match(r"^[A-Z]+-[\w-]+$", vid) and not vid.startswith("RETIRE"):
        return f"https://osv.dev/vulnerability/{vid}"
    return ""


def clean(v, limit=MAX_CELL):
    if v is None:
        return ""
    if isinstance(v, (set, list, tuple)):
        v = ", ".join(sorted(str(x) for x in v if x))
    s = _ILLEGAL.sub("", str(v))
    # neutralise formula injection from scanner-provided text
    if s[:1] in ("=", "+", "-", "@") and not re.match(r"^-?\d", s):
        s = "'" + s
    return s if len(s) <= limit else s[: limit - 1] + "…"


class Report:
    def __init__(self, path: Path):
        self.path = path
        self.wb = xlsxwriter.Workbook(str(path), {"strings_to_urls": False, "strings_to_formulas": False,
                                                  "nan_inf_to_errors": True})
        self.wb.set_properties({"title": "Vulnerability Scan Report", "subject": "Shipped deliverables",
                                "comments": "Generated by vulnscan"})
        f = self.wb.add_format
        base = {"font_name": "Segoe UI", "font_size": 10, "valign": "top"}
        self.base = base
        self.f = {
            "title": f({**base, "font_size": 22, "bold": True, "font_color": BRAND}),
            "subtitle": f({**base, "font_size": 11, "font_color": MUTED}),
            "h2": f({**base, "font_size": 13, "bold": True, "font_color": BRAND, "bottom": 2,
                     "bottom_color": BRAND}),
            "label": f({**base, "font_color": MUTED}),
            "value": f({**base, "font_color": INK}),
            "bold": f({**base, "bold": True, "font_color": INK}),
            "text": f({**base}),
            "wrap": f({**base, "text_wrap": True}),
            "muted": f({**base, "font_color": MUTED}),
            "mono": f({**base, "font_name": "Consolas", "font_size": 9}),
            "int": f({**base, "num_format": "#,##0", "align": "center"}),
            "score": f({**base, "num_format": "0.0", "align": "center"}),
            "pct": f({**base, "num_format": "0.00%", "align": "center"}),
            "center": f({**base, "align": "center"}),
            "link": f({**base, "font_color": "#1D4ED8", "underline": 1}),
            "hdr": f({**base, "bold": True, "font_color": "#FFFFFF", "bg_color": BRAND, "valign": "vcenter",
                      "align": "center",
                      "text_wrap": True, "border": 1, "border_color": BRAND}),
            "kpi_num": {}, "kpi_lbl": {},
            "kev": f({**base, "bold": True, "font_color": "#FFFFFF", "bg_color": "#7F1D1D", "align": "center"}),
            "note": f({**base, "font_color": "#92400E", "bg_color": "#FEF3C7", "text_wrap": True,
                       "border": 1, "border_color": "#FCD34D"}),
            "ok": f({**base, "font_color": "#166534", "bold": True}),
            "banner": f({**base, "font_size": 12, "bold": True, "font_color": "#FFFFFF", "bg_color": "#B91C1C",
                         "valign": "vcenter"}),
            "bad": f({**base, "font_color": "#B91C1C", "bold": True}),
        }
        self.sev_fmt = {s: f({**base, "bold": True, "bg_color": bg, "font_color": fg, "align": "center"})
                        for s, (bg, fg) in SEV_COLORS.items()}
        self.prio_fmt = {p: f({**base, "bold": True, "bg_color": bg, "font_color": fg, "align": "center"})
                         for p, (bg, fg) in PRIO_COLORS.items()}
        for key, (bg, fg) in {**SEV_COLORS, "TOTAL": ("#1E3A5F", "#FFFFFF"), "KEV": ("#7F1D1D", "#FFFFFF"),
                              "EOL": ("#4B5563", "#FFFFFF"), "P1": PRIO_COLORS["P1"]}.items():
            self.f["kpi_num"][key] = f({**base, "font_size": 24, "bold": True, "bg_color": bg, "num_format": "#,##0",
                                        "font_color": fg, "align": "center", "valign": "vcenter"})
            self.f["kpi_lbl"][key] = f({**base, "font_size": 9, "bold": True, "bg_color": bg,
                                        "font_color": fg, "align": "center", "valign": "vcenter"})

    # ------------------------------------------------------------------
    def _cf_sev(self, ws, first_row, last_row, col):
        if last_row < first_row:
            return
        for s in SEVS:
            ws.conditional_format(first_row, col, last_row, col, {
                "type": "cell", "criteria": "==", "value": f'"{s.title()}"', "format": self.sev_fmt[s]})

    def _cf_prio(self, ws, first_row, last_row, col):
        if last_row < first_row:
            return
        for p in PRIO:
            ws.conditional_format(first_row, col, last_row, col, {
                "type": "cell", "criteria": "==", "value": f'"{p}"', "format": self.prio_fmt[p]})

    def _cf_kev(self, ws, first_row, last_row, col):
        if last_row >= first_row:
            ws.conditional_format(first_row, col, last_row, col, {
                "type": "cell", "criteria": "==", "value": '"YES"', "format": self.f["kev"]})

    def _table(self, ws, name: str, columns: list[tuple], rows: list[list], first_row: int = 0,
               freeze_cols: int = 0):
        """columns: (header, width, format_key|None)"""
        n = len(rows)
        last_row = first_row + max(n, 1)
        cols = [{"header": h, "header_format": self.f["hdr"],
                 **({"format": self.f[fk]} if fk else {})} for h, _, fk in columns]
        ws.add_table(first_row, 0, last_row, len(columns) - 1, {
            "name": name, "columns": cols, "style": "Table Style Light 1",
            "data": rows if rows else [[""] * len(columns)], "autofilter": True})
        for i, (_, w, _) in enumerate(columns):
            ws.set_column(i, i, w)
        ws.set_row(first_row, 30)
        ws.freeze_panes(first_row + 1, freeze_cols)
        ws.set_landscape()
        ws.set_paper(9)  # A4
        ws.repeat_rows(first_row)
        ws.set_margins(0.3, 0.3, 0.5, 0.5)
        ws.set_footer("&L&8vulnscan · &A&R&8page &P / &N")
        return first_row + 1, last_row

    # ------------------------------------------------------------------
    def build(self, meta: dict, findings: list[dict], components: list[dict], eol: list[dict],
              binaries: list[dict], coverage: list[dict]) -> Path:
        findings = sorted(findings, key=lambda f: (PRIO.index(f["priority"]), SEV_RANK[f["severity"]],
                                                   -(f["cvss_score"] or 0), f["repo"], f["path"], f["vuln_id"]))
        uniq = self._unique_vulns(findings)
        comp_rows = self._component_rows(components, findings, eol)
        self._summary(meta, findings, uniq, comp_rows, eol, binaries, coverage)
        self._findings(findings)
        self._vulns(uniq)
        self._components(comp_rows)
        self._eol(eol)
        self._binaries(binaries)
        self._coverage(meta, coverage)
        self.wb.close()
        return self.path

    # ------------------------------------------------------------------
    @staticmethod
    def _unique_vulns(findings):
        g: dict[tuple, dict] = {}
        for f in findings:
            key = (f["vuln_id"], f["component"].lower(), f["version"])
            u = g.get(key)
            if not u:
                u = g[key] = {**f, "files": set(), "repos": set()}
            u["files"].add((f["repo"], f["path"]))
            u["repos"].add(f["repo"])
            u["sources"] = u["sources"] | f["sources"]
        return sorted(g.values(), key=lambda u: (PRIO.index(u["priority"]), SEV_RANK[u["severity"]],
                                                -(u["cvss_score"] or 0), u["vuln_id"]))

    @staticmethod
    def _component_rows(components, findings, eol):
        vul = defaultdict(lambda: {"ids": set(), "kev": set(), "max": "UNKNOWN", "p1": set()})
        for f in findings:
            v = vul[(f["component"].lower(), f["version"])]
            v["ids"].add(f["vuln_id"])
            if f.get("kev"):
                v["kev"].add(f["vuln_id"])
            if f["priority"] == "P1":
                v["p1"].add(f["vuln_id"])
            if SEV_RANK[f["severity"]] < SEV_RANK[v["max"]]:
                v["max"] = f["severity"]
        eol_map = {(e["name"].lower(), e["version"]): e for e in eol}
        agg: dict[tuple, dict] = {}
        for c in components:
            key = (c["name"].lower(), c["version"], c["type"])
            a = agg.setdefault(key, {**c, "repos": set(), "paths": set(), "sources": set()})
            a["repos"].add(c["repo"])
            a["paths"].add(f"{c['repo']}/{c['path']}")
            a["sources"].add(c["source"])
        rows = []
        for (name, version, _), a in agg.items():
            v = vul.get((name, version)) or vul.get((a["name"].split("/")[-1].lower(), version)) or \
                {"ids": set(), "kev": set(), "max": "", "p1": set()}
            e = eol_map.get((a["name"].lower(), version))
            rows.append({**a, "vulns": len(v["ids"]), "kev": len(v["kev"]), "p1": len(v["p1"]),
                         "max": v["max"] if v["ids"] else "", "eol": e["status"] if e else ""})
        rows.sort(key=lambda r: (-r["p1"], -r["kev"], SEV_RANK.get(r["max"], 9), -r["vulns"], r["name"]))
        return rows

    # ------------------------------------------------------------------
    def _summary(self, meta, findings, uniq, comp_rows, eol, binaries, coverage):
        ws = self.wb.add_worksheet("Summary")
        ws.hide_gridlines(2)
        ws.set_zoom(100)
        ws.set_landscape()
        ws.set_paper(9)
        ws.fit_to_pages(1, 0)
        ws.set_margins(0.4, 0.4, 0.5, 0.5)
        ws.set_column(0, 0, 2)
        ws.set_column(1, 12, 15)
        F = self.f
        ws.write(1, 1, "Vulnerability Scan Report", F["title"])
        ws.write(2, 1, f"Shipped deliverables · {', '.join(r['name'] for r in meta['repos'])} · "
                       f"scanned {meta['started']} ({meta['duration']})", F["subtitle"])
        if meta.get("incomplete"):
            ws.merge_range(3, 1, 3, 12, "⚠  SCAN INCOMPLETE - this report is NOT an all-clear. "
                                        "See 'Attention' below and the Coverage sheet.", F["banner"])
            ws.set_row(3, 26)

        sev_counts = Counter(f["severity"] for f in findings)
        kev_ids = {f["vuln_id"] for f in findings if f.get("kev")}
        p1 = sum(1 for f in findings if f["priority"] == "P1")
        tiles = [("TOTAL", len(findings), "FINDINGS"), ("P1", p1, "PRIORITY 1"),
                 ("KEV", len(kev_ids), "KNOWN EXPLOITED"), ("CRITICAL", sev_counts["CRITICAL"], "CRITICAL"),
                 ("HIGH", sev_counts["HIGH"], "HIGH"), ("MEDIUM", sev_counts["MEDIUM"], "MEDIUM"),
                 ("EOL", len({(e["product"], e["version"]) for e in eol if e["status"] == "End of life"}), "END-OF-LIFE")]
        col = 1
        for key, num, label in tiles:
            ws.merge_range(4, col, 5, col + 0, num, F["kpi_num"][key])
            ws.write(6, col, label, F["kpi_lbl"][key])
            col += 1
        ws.set_row(4, 24)
        ws.set_row(5, 24)
        ws.write(7, 1, f"{len(uniq):,} distinct vulnerability/component pairs · "
                       f"{len({f['vuln_id'] for f in findings}):,} distinct vulnerability IDs · "
                       f"{len({(f['repo'], f['path']) for f in findings}):,} affected files", F["muted"])

        # per repository
        r = 9
        ws.merge_range(r, 1, r, 12, "By repository", F["h2"])
        ws.set_row(r, 24)
        r += 1
        hdr = ["Repository", "Revision", "Files", "Binaries", "Components", "Critical", "High", "Medium",
               "Low", "Other", "KEV", "Status"]
        for i, h in enumerate(hdr):
            ws.write(r, 1 + i, h, F["hdr"])
        chart_first = r + 1
        by_repo = defaultdict(Counter)
        kev_repo = defaultdict(set)
        for f in findings:
            by_repo[f["repo"]][f["severity"]] += 1
            if f.get("kev"):
                kev_repo[f["repo"]].add(f["vuln_id"])
        cov = {c["repo"]: c for c in coverage}
        for repo in meta["repos"]:
            r += 1
            c = by_repo[repo["name"]]
            cv = cov.get(repo["name"], {})
            failed = [k for k, v in cv.get("engines", {}).items() if v.get("status") != "ok"]
            if cv.get("archives_failed"):
                failed.append("archives")
            rev = str(repo.get("revision") or "?")
            vals = [repo["name"], rev if rev in ("local", "?") else f"r{rev}", cv.get("files", 0), cv.get("binaries", 0),
                    cv.get("components", 0), c["CRITICAL"], c["HIGH"], c["MEDIUM"], c["LOW"],
                    c["NEGLIGIBLE"] + c["UNKNOWN"], len(kev_repo[repo["name"]])]
            for i, v in enumerate(vals):
                fmt = F["bold"] if i == 0 else F["int"] if isinstance(v, int) else F["text"]
                ws.write(r, 1 + i, v, fmt)
            if cv.get("error"):
                ws.write(r, 12, "FAILED", F["bad"])
            elif failed:
                ws.write(r, 12, "Incomplete: " + ", ".join(failed), F["bad"])
            else:
                ws.write(r, 12, "Complete", F["ok"])
        chart_last = r
        for col_i, sev in zip(range(6, 10), ["CRITICAL", "HIGH", "MEDIUM", "LOW"], strict=True):
            self._cf_cells_bar(ws, chart_first, chart_last, col_i, SEV_COLORS[sev][0])

        # chart
        if meta["repos"]:
            ch = self.wb.add_chart({"type": "bar", "subtype": "stacked"})
            for col_i, sev in zip(range(6, 10), ["CRITICAL", "HIGH", "MEDIUM", "LOW"], strict=True):
                ch.add_series({"name": sev.title(),
                               "categories": ["Summary", chart_first, 1, chart_last, 1],
                               "values": ["Summary", chart_first, col_i, chart_last, col_i],
                               "fill": {"color": SEV_COLORS[sev][0]}, "border": {"none": True},
                               "gap": 60})
            ch.set_title({"name": "Findings by severity", "name_font": {"size": 11, "color": INK}})
            ch.set_legend({"position": "bottom", "font": {"size": 9}})
            ch.set_x_axis({"major_gridlines": {"visible": True, "line": {"color": LINE}},
                           "num_font": {"size": 9}})
            ch.set_y_axis({"reverse": True, "num_font": {"size": 9}})
            ch.set_chartarea({"border": {"none": True}})
            ch.set_size({"width": 760, "height": 90 + 34 * len(meta["repos"])})
            r += 2
            ws.insert_chart(r, 1, ch)
            r += int((90 + 34 * len(meta["repos"])) / 20) + 2

        # top risky components
        r += 1
        ws.merge_range(r, 1, r, 12, "Highest-risk components", F["h2"])
        ws.set_row(r, 24)
        r += 1
        for i, h in enumerate(["Component", "Version", "Type", "Vulns", "P1", "KEV", "Max severity",
                               "End of life", "Files", "Repositories"]):
            ws.write(r, 1 + i, h, F["hdr"])
        top = [c for c in comp_rows if c["vulns"] or c["eol"]][:20]
        start = r + 1
        for c in top:
            r += 1
            vals = [c["name"], c["version"], c["type"], c["vulns"], c["p1"], c["kev"],
                    c["max"].title() if c["max"] else "", c["eol"], len(c["paths"]), ", ".join(sorted(c["repos"]))]
            for i, v in enumerate(vals):
                ws.write(r, 1 + i, clean(v) if isinstance(v, str) else v,
                         F["bold"] if i == 0 else F["int"] if isinstance(v, int) else F["text"])
        self._cf_sev(ws, start, r, 7)
        if not top:
            r += 1
            ws.write(r, 1, "No vulnerable or end-of-life components identified.", F["muted"])

        # warnings
        notes = list(meta.get("notes", []))
        for c in coverage:
            if c.get("error"):
                notes.append(f"{c['repo']}: scan FAILED - {c['error']}")
            for eng, v in c.get("engines", {}).items():
                if v.get("status") != "ok":
                    notes.append(f"{c['repo']}: engine {eng} did not complete - {v.get('error', '')}")
            if c.get("archives_failed"):
                notes.append(f"{c['repo']}: {c['archives_failed']} archive(s) could not be (fully) extracted - "
                             f"their contents were NOT scanned (see Coverage)")
            if c.get("archives_acknowledged"):
                notes.append(f"{c['repo']}: {len(c['archives_acknowledged'])} archive(s) not extracted, "
                             f"acknowledged as accepted gaps (see Coverage)")
            if c.get("symlinks"):
                notes.append(f"{c['repo']}: {len(c['symlinks'])} symbolic link(s) were recorded but not followed "
                             f"(see Coverage)")
        review = sum(1 for b in binaries if b.get("review"))
        if review:
            notes.append(f"{review} third-party binaries could not be matched to a known component; "
                         f"they are flagged for manual review on the Binaries sheet.")
        r += 2
        ws.merge_range(r, 1, r, 12, "Attention", F["h2"])
        ws.set_row(r, 24)
        if not notes and meta.get("incomplete"):
            notes = ["Scan incomplete - see the Coverage sheet."]
        for n in notes or ["No scan errors. All engines completed and passed their self-test, "
                           "and the vulnerability data was current."]:
            r += 1
            ws.merge_range(r, 1, r, 12, clean(n), F["note"] if notes else F["ok"])
            ws.set_row(r, 30 if len(n) > 120 else 18)

        # methodology
        r += 2
        ws.merge_range(r, 1, r, 12, "Method", F["h2"])
        ws.set_row(r, 24)
        method = [
            ("Inventory", "Every file of each repository is checked out from SVN, archives (zip/msi/cab/7z/...) "
                          "are extracted recursively, and every file is hashed (SHA-256)."),
            ("Packages", "Syft builds an SBOM (Python, npm, .NET, Java, Go, Rust...); Grype and osv-scanner "
                         "match it independently against the Anchore (NVD, GitHub, vendor advisories) and "
                         "OSV.dev databases."),
            ("Binaries", "Every DLL/EXE/PYD is identified from its Windows version resource and from embedded "
                         "version signatures (catches statically linked libraries), then matched via NVD CPE data."),
            ("JavaScript", "retire.js detects vulnerable standalone JavaScript libraries."),
            ("Exploitation", "CISA Known Exploited Vulnerabilities (KEV) and FIRST EPSS scores from the same "
                             "database snapshot. Unsupported runtimes are flagged from endoflife.date / Microsoft."),
            ("Priority", "P1 = on CISA KEV, or Critical with EPSS ≥ 10%.  P2 = Critical, or High with EPSS ≥ 5%.  "
                         "P3 = High/Medium.  P4 = Low/Negligible/Unknown."),
            ("Confidence", "high = exact package/version evidence; medium = CPE/name-based match that may need "
                           "confirmation (e.g. vendor-patched builds)."),
        ]
        for k, v in method:
            r += 1
            ws.write(r, 1, k, F["bold"])
            ws.merge_range(r, 2, r, 12, v, F["wrap"])
            ws.set_row(r, 28)
        r += 2
        ws.write(r, 1, "Toolchain", F["bold"])
        ws.merge_range(r, 2, r, 12, " · ".join(f"{k} {v}" for k, v in meta["tools"].items()), F["wrap"])
        ws.set_row(r, 28)
        for k, v in meta["databases"].items():
            r += 1
            ws.write(r, 1, k, F["bold"])
            ws.merge_range(r, 2, r, 12, clean(v), F["muted"])
        ws.activate()

    def _cf_cells_bar(self, ws, r1, r2, col, color):
        if r2 >= r1:
            ws.conditional_format(r1, col, r2, col, {"type": "data_bar", "bar_color": color,
                                                     "bar_solid": True, "bar_no_border": True})

    # ------------------------------------------------------------------
    def _findings(self, findings):
        ws = self.wb.add_worksheet("Findings")
        cols = [("Priority", 9, "center"), ("Severity", 11, "center"), ("CVSS", 7, "score"),
                ("KEV", 6, "center"), ("EPSS", 8, "pct"), ("Vulnerability", 17, None),
                ("Repository", 13, None), ("File path", 60, None), ("Component", 22, None),
                ("Installed", 14, None), ("Fixed in", 16, None), ("Type", 12, None),
                ("Title / description", 80, None), ("Detected by", 18, None), ("Confidence", 11, "center"),
                ("Evidence", 45, "muted"), ("CWE", 14, None), ("Published", 11, "center"),
                ("KEV added", 11, "center"), ("KEV due", 11, "center"), ("Ransomware use", 11, "center"),
                ("Aliases", 22, None), ("CVSS vector", 40, "mono"), ("References", 60, "muted"),
                ("Revision", 9, "center")]
        rows = []
        for f in findings:
            kev = f.get("kev") or {}
            desc = f["title"] + (" — " if f["title"] and f["description"] else "") if f["title"] != f["description"] else ""
            desc = clean((desc + (f["description"] or "")).replace("\n", " "), 2000)
            rows.append([f["priority"], f["severity"].title(), f["cvss_score"], "YES" if kev else "",
                         f.get("epss"), f["vuln_id"], f["repo"], clean(f["path"]), clean(f["component"]),
                         clean(f["version"]), clean(f["fixed"] or ("not fixed" if f["fix_state"] == "not-fixed" else "")),
                         clean(f["comp_type"]), desc, clean(f["sources"]), f["confidence"], clean(f["evidence"], 500),
                         clean(f["cwe"]), f["published"], (kev.get("date_added") or kev.get("dateAdded") or "")[:10],
                         (kev.get("due_date") or kev.get("dueDate") or "")[:10],
                         kev.get("known_ransomware_campaign_use") or kev.get("knownRansomwareCampaignUse") or "",
                         clean(f["aliases"]), clean(f["cvss_vector"]), clean(" ".join(f["refs"][:5]), 1000),
                         f.get("revision", "")])
